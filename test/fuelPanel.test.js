import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { parseHTML } from "linkedom";
import { mission } from "../js/models/missions.js";
import { initializeFuelPanel, updateFuelPlanningPanel } from "../js/ui/fuelPanel.js";
import { setMissionRefreshHandler } from "../js/core/missionEngine.js";

test("Full and arrows respect model capacity, partial steps and zero", () => {
    const { window, document } = parseHTML(readFileSync(new URL("../index.html", import.meta.url), "utf8"));
    globalThis.window = window; globalThis.document = document; globalThis.CustomEvent = window.CustomEvent;
    mission.aircraft.model = { ...mission.aircraft.model, maxFuel: 1140 };
    const leg = mission.legs[0];
    leg.fuel.onboard = 1100;
    initializeFuelPanel();
    setMissionRefreshHandler(updateFuelPlanningPanel);
    const field = name => document.querySelector(`[data-field="${name}"]`);
    const plus = field("fuelOnBoard").querySelector(".stepper-plus");
    const minus = field("fuelOnBoard").querySelector(".stepper-minus");
    plus.click();
    assert.equal(leg.fuel.onboard, 1140);
    assert.equal(plus.getAttribute("aria-disabled"), "true");
    plus.click();
    assert.equal(leg.fuel.onboard, 1140);
    assert.equal(field("fuelLimitMessage").textContent, "Combustível máximo atingido");
    minus.click();
    assert.equal(plus.getAttribute("aria-disabled"), "false");
    leg.fuel.onboard = 40;
    minus.click();
    assert.equal(leg.fuel.onboard, 0);
    assert.equal(minus.disabled, true);
    leg.automatic.fuel = true;
    field("fullFuel").click();
    assert.equal(leg.fuel.onboard, 1140);
    assert.equal(leg.automatic.fuel, false);
    mission.aircraft.model = { ...mission.aircraft.model, maxFuel: 500, fuel: { defaultUnit: "KG" } };
    updateFuelPlanningPanel();
    field("fullFuel").click();
    assert.equal(leg.fuel.onboard, 500);
    assert.equal(field("fuelOnBoard").querySelector(".stepper-unit").textContent, "KG");
});
