import test from "node:test";
import assert from "node:assert/strict";
import { mission, missionLegs } from "../js/models/missions.js";
import { recalculateMission, addMissionLeg, selectMissionLeg, removeMissionLeg, updateMissionField } from "../js/core/missionEngine.js";
import { departureAfterArrival } from "../js/core/legSchedule.js";
import { lbToKg } from "../js/utils/helpers.js";
import { createRouteLayer, updateRouteLayer, synchronizeRouteLayer } from "../map/mission/routeLayer.js";

const airport = (icao, latitude, longitude) => ({ icao, type: "AIRPORT", position: { latitude, longitude } });
const a = airport("SBFZ", -3.77, -38.53);
const b = airport("SBRF", -8.12, -34.92);
const c = airport("SBSV", -12.91, -38.33);

test("three-leg mission propagates UTC times and fuel, preserving manual overrides", () => {
    const first = missionLegs.active();
    first.route.origin = a;
    first.route.destination = b;
    first.route.alternate = c;
    Object.assign(first.schedule, { date: "2026-12-31", etd: "23:30" });
    first.fuel.onboard = 5000;
    first.payload.data.total.weight = 200;
    recalculateMission();
    assert.equal(first.schedule.etaDate, "2027-01-01");
    assert.equal(first.fuel.arrival, 5000 - first.fuel.taxi - first.fuel.flight - first.fuel.procedure);
    assert.equal(first.weight.landingFuel, lbToKg(first.fuel.arrival));
    const second = addMissionLeg();
    second.route.destination = c;
    second.refuel = 400;
    recalculateMission();
    assert.equal(second.route.origin, b);
    assert.equal(second.schedule.etd, departureAfterArrival(first.schedule).etd);
    assert.equal(second.fuel.onboard, Math.floor(first.fuel.arrival / 100) * 100 + 400);
    assert.equal(second.weight.payload, 200);
    const third = addMissionLeg();
    third.route.destination = a;
    recalculateMission();
    assert.equal(third.route.origin, c);
    assert.equal(third.schedule.etd, departureAfterArrival(second.schedule).etd);
    selectMissionLeg(second.id);
    updateMissionField({ target: mission.route, property: "origin" }, a);
    second.automatic.departure = false;
    Object.assign(second.schedule, { date: "2027-01-02", etd: "14:00" });
    second.automatic.fuel = false;
    second.fuel.onboard = 3000;
    second.fuel.manual.taxi = true;
    second.fuel.taxi = 50;
    first.route.destination = c;
    first.schedule.etd = "20:00";
    first.fuel.onboard = 4000;
    recalculateMission();
    assert.equal(second.route.origin, a);
    assert.equal(second.schedule.etd, "14:00");
    assert.equal(second.fuel.onboard, 3000);
    assert.equal(second.fuel.taxi, 50);
    assert.equal(third.schedule.etd, departureAfterArrival(second.schedule).etd);
    assert.equal(third.schedule.date, "2027-01-02");

    const layer = createRouteLayer();
    updateRouteLayer(layer);
    const segments = layer.getSource().getFeatures().filter(f => f.get("type") === "route-leg");
    assert.equal(segments.length, 3);
    assert.equal(segments.filter(f => f.get("missionLegActive")).length, 1);
    removeMissionLeg(second.id);
    assert.equal(mission.activeLegId, first.id);
    assert.equal(third.schedule.etd, departureAfterArrival(first.schedule).etd);
    assert.equal(third.fuel.onboard, Math.floor(first.fuel.arrival / 100) * 100);
    removeMissionLeg(third.id);
    assert.equal(mission.legs.length, 1);
});

test("map synchronizes whether it starts before or after mission recovery", () => {
    const leg = missionLegs.active();
    const events = new EventTarget();
    leg.route.origin = undefined;
    leg.route.destination = undefined;
    leg.route.alternate = undefined;
    const early = createRouteLayer();
    const stopEarly = synchronizeRouteLayer(early, events);
    assert.equal(early.getSource().getFeatures().length, 0);
    leg.route.origin = a;
    leg.route.destination = b;
    recalculateMission();
    events.dispatchEvent(new Event("mission-route-updated"));
    assert.ok(early.getSource().getFeatures().some(feature => feature.get("type") === "route-leg"));
    const late = createRouteLayer();
    const stopLate = synchronizeRouteLayer(late, events);
    assert.equal(late.getSource().getFeatures().length, early.getSource().getFeatures().length);
    stopEarly();
    stopLate();
});
