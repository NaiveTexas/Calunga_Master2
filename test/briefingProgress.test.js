test("guidance points to missing data and only explains fields on their own page", () => {
    const route = { allowed: [true, true, false, false, false], message: "Preencha a rota" };
    assert.deepEqual(briefingGuidance(route, 0), { target: 1, message: "Avance para a rota" });
    assert.deepEqual(briefingGuidance(route, 1), { target: null, message: "Preencha a rota" });
    const fuel = { allowed: [true, true, true, false, false], message: "Combustível a bordo abaixo do mínimo" };
    assert.deepEqual(briefingGuidance(fuel, 0), { target: 2, message: "Avance para o combustível" });
    assert.equal(briefingGuidance(fuel, 1).target, 2);
    assert.equal(briefingGuidance(fuel, 2).message, fuel.message);
    const complete = { allowed: [true, true, true, true, true], message: "" };
    assert.deepEqual(briefingGuidance(complete, 3), { target: 4, message: "Avance para o dashboard" });
    assert.equal(briefingGuidance(complete, 4).target, null);
    assert.notEqual(briefingGuidance(complete, 0).target, 1);
});
test("tabs and arrows enforce gates and route controls follow flight order", () => {
    const { document, window } = parseHTML(readFileSync(new URL("../index.html", import.meta.url), "utf8"));
    globalThis.document = document; globalThis.window = window;
    mission.settings.modelChosen = false; mission.settings.registrationChosen = false;
    initializeBriefingNavigation();
    const tabs = [...document.querySelectorAll(".briefing-tab")];
    assert.equal(tabs[1].disabled, true);
    document.getElementById("briefingNext").click();
    assert.ok(document.getElementById("missionPanel").classList.contains("active"));
    const leg = missionLegs.active();
    mission.settings.modelChosen = true; mission.settings.registrationChosen = true;
    leg.route.origin = { position: { latitude: 0, longitude: 0 } };
    leg.route.destination = { position: { latitude: 1, longitude: 1 } };
    leg.schedule.date = "2026-09-16"; leg.schedule.etd = "12:00";
    leg.flightLevel = "FL100"; leg.fuel.total = 1000; leg.fuel.onboard = 1000;
    leg.route.alternate = leg.route.origin;
    assert.equal(briefingProgress(mission, leg).allowed[2], false);
    leg.routeConfirmed = routeConfirmation(leg);
    leg.payload.entered = true;
    leg.weightReviewed = weightReviewSignature(mission, leg);
    window.dispatchEvent(new window.Event("mission-updated"));
    assert.ok(tabs.every(tab => !tab.disabled));
    leg.payload.entered = false;
    assert.equal(briefingProgress(mission, leg).allowed[4], false);
    leg.payload.entered = true;
    leg.weight.payload = 0;
    leg.weightReviewed = weightReviewSignature(mission, leg);
    tabs[4].click();
    assert.ok(document.getElementById("dashboardPanel").classList.contains("active"));
    leg.fuel.onboard = 999;
    window.dispatchEvent(new window.Event("mission-updated"));
    assert.ok(document.getElementById("fuelPanel").classList.contains("active"));
    assert.equal(document.getElementById("briefingNext").disabled, true);
    assert.equal(document.getElementById("waypointPanel").nextElementSibling.contains(document.getElementById("destination")), true);
    assert.equal(document.getElementById("eta").tagName, "OUTPUT");
});
test("guided steps require explicit aircraft selection, valid route and sufficient fuel", () => {
    const mission = { settings: { modelChosen: false, registrationChosen: false }, aircraft: { model: { name: "TEST" }, registration: { model: { name: "TEST" } } } };
    const leg = { flightLevel: "FL100", route: { origin: { position: { latitude: 0, longitude: 0 } }, destination: { position: { latitude: 1, longitude: 1 } } }, schedule: { date: "2026-09-16", etd: "12:00" }, fuel: { onboard: 1000, total: 1000 } };
    assert.deepEqual(briefingProgress(mission, leg).allowed, [true, false, false, false, false]);
    mission.settings.modelChosen = true;
    assert.equal(briefingProgress(mission, leg).allowed[1], false);
    mission.settings.registrationChosen = true;
    assert.equal(briefingProgress(mission, leg).routeReady, false);
    leg.route.alternate = leg.route.origin;
    leg.payload = { entered: true }; leg.weight = { payload: 0 };
    leg.weightReviewed = weightReviewSignature(mission, leg);
    assert.ok(briefingProgress(mission, leg).allowed.every(Boolean));
    leg.fuel.onboard = 999;
    assert.deepEqual(briefingProgress(mission, leg).allowed, [true, true, true, false, false]);
    leg.schedule.date = "2026-02-30";
    assert.equal(briefingProgress(mission, leg).allowed[2], false);
    leg.schedule.date = "2026-09-16";
    leg.fuel.onboard = 1000;
    mission.settings = {}; // Valid legacy drafts need no new confirmation.
    assert.ok(briefingProgress(mission, leg).allowed.every(Boolean));
    const secondLeg = { ...leg, route: { ...leg.route, destination: null } };
    assert.equal(briefingProgress(mission, secondLeg).allowed[2], false);
});
